// Заполняет элементы с data-k / data-list
window.fillK = function () {
  document.querySelectorAll('[data-k]').forEach(el => { el.textContent = K[el.dataset.k]; });
  document.querySelectorAll('[data-topics]').forEach(el => {
    const [a, b] = el.dataset.topics.split('-').map(Number);
    const tpl = el.dataset.tpl || '<li><b>{n}</b><span>{t}</span></li>';
    el.innerHTML = K.topics.slice(a - 1, b).map((t, i) => tpl.replace('{n}', String(a + i).padStart(2, '0')).replace('{t}', t)).join('');
  });
  document.querySelectorAll('[data-goals]').forEach(el => {
    const tpl = el.dataset.tpl || '<div><b>{n}</b><p>{t}</p></div>';
    el.innerHTML = K.goals.map((t, i) => tpl.replace('{n}', String(i + 1).padStart(2, '0')).replace('{t}', t)).join('');
  });
  document.querySelectorAll('[data-laws]').forEach(el => {
    const tpl = el.dataset.tpl || '<span>{t}</span>';
    el.innerHTML = K.laws.map(t => tpl.replace('{t}', t)).join('');
  });
};
